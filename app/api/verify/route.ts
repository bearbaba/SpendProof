import { NextRequest, NextResponse } from 'next/server';
import { verifyDecision } from '../../../lib/attestation';

export const runtime = 'nodejs';
export async function POST(req: NextRequest) {
  const secret = process.env.SPENDPROOF_AUDIT_SECRET;
  if (!secret || secret.length < 32) {
    return NextResponse.json({authentic:false,error:'Decision verification is not configured.'},{status:503});
  }
  let data: unknown;
  try {
    if (Number(req.headers.get('content-length') || 0) > 12000) {
      return NextResponse.json({authentic:false,error:'Payload too large.'},{status:413});
    }
    data = await req.json();
  } catch {
    return NextResponse.json({authentic:false,error:'Malformed JSON.'},{status:400});
  }
  const candidate = data && typeof data === 'object' ? (data as Record<string, unknown>).attestation : null;
  const authentic = verifyDecision(secret, candidate);
  return NextResponse.json({
    authentic,
    assurance: authentic
      ? 'This decision record was signed by this SpendProof server. It does not verify provider identity or any payment.'
      : 'Signature missing, invalid, or generated by a different SpendProof server.',
    providerVerified: false,
    paymentVerified: false,
  },{headers:{'Cache-Control':'no-store'}});
}
